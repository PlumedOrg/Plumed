//! Build script: registers every app command in a Tauri app manifest.
//!
//! Without a manifest, any command of `generate_handler!` can be invoked by
//! every window, overlay included. With one, each command gets an
//! `allow-<command>` permission and a window can only call the commands its
//! capability grants. The list of commands is read from the single place that
//! defines it (`generate_handler![...]` in `src/lib.rs`), so it cannot drift.
//! The permission set `main-commands` (all commands, granted to the main
//! window in `capabilities/default.json`) is written to
//! `permissions/main-commands.toml`, which is committed: Tauri only reads
//! permission files from disk. Commands the overlay may call are listed by
//! hand in `capabilities/overlay.json`.

use std::fs;

const LIB_RS: &str = "src/lib.rs";
const MAIN_SET_FILE: &str = "permissions/main-commands.toml";

/// Command names listed in `tauri::generate_handler![ ... ]` (one bare
/// identifier per entry, as rustfmt lays them out).
fn handler_commands(lib_rs: &str) -> Vec<String> {
    let start = lib_rs
        .find("generate_handler![")
        .expect("generate_handler! not found in src/lib.rs")
        + "generate_handler![".len();
    let len = lib_rs[start..]
        .find(']')
        .expect("generate_handler! list is not closed");
    let commands: Vec<String> = lib_rs[start..start + len]
        .split(',')
        .map(|c| c.trim().to_string())
        .filter(|c| !c.is_empty())
        .collect();
    for c in &commands {
        assert!(
            c.chars().all(|ch| ch.is_ascii_alphanumeric() || ch == '_'),
            "unsupported entry in generate_handler!: {c:?} (use plain `use`d identifiers)"
        );
    }
    commands
}

fn main_set_toml(commands: &[String]) -> String {
    let mut out = String::from(
        "# Generated by build.rs from generate_handler! in src/lib.rs. Do not edit.\n\n\
         [[set]]\nidentifier = \"main-commands\"\n\
         description = \"Every app command (main window only; the overlay gets a short list, see capabilities/overlay.json)\"\n\
         permissions = [\n",
    );
    for c in commands {
        out.push_str(&format!("    \"allow-{}\",\n", c.replace('_', "-")));
    }
    out.push_str("]\n");
    out
}

fn main() {
    println!("cargo:rerun-if-changed={LIB_RS}");
    let lib_rs = fs::read_to_string(LIB_RS).expect("cannot read src/lib.rs");
    let commands = handler_commands(&lib_rs);
    assert!(
        !commands.is_empty(),
        "no command found in generate_handler!"
    );

    let toml = main_set_toml(&commands);
    if fs::read_to_string(MAIN_SET_FILE).ok().as_deref() != Some(toml.as_str()) {
        fs::create_dir_all("permissions").expect("cannot create permissions/");
        fs::write(MAIN_SET_FILE, toml).expect("cannot write main-commands.toml");
    }

    // `commands()` wants 'static slices; the build script is short-lived.
    let names: &'static [&'static str] = Box::leak(
        commands
            .into_iter()
            .map(|c| &*Box::leak(c.into_boxed_str()))
            .collect::<Vec<&'static str>>()
            .into_boxed_slice(),
    );
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(names)),
    )
    .expect("failed to run tauri-build");
}
